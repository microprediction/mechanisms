"""Parimutuel (pool betting) markets.

In a parimutuel market all wagers on a set of mutually exclusive, exhaustive
outcomes are pooled. After the outcome is known, the operator removes a fixed
fraction (the *takeout* ``tau``) and distributes the remaining pool pro rata to
the holders of winning tickets. Crucially the odds are *endogenous*: they are
fixed only when betting closes, and the operator carries no outcome risk — the
bettors collectively fund every payout.

Invented by Pierre Oller in the 1860s; mechanised by the totalisator. The pool
fractions ``W_i / W`` are the market's implied probabilities, which makes the
parimutuel a simple information-aggregation mechanism (subject to the well-known
favourite-longshot bias; see Thaler & Ziemba 1988, Snowberg & Wolfers 2010).

References
----------
- Thaler, R. & Ziemba, W. (1988). "Anomalies: Parimutuel Betting Markets."
  J. Economic Perspectives 2(2).
- Pennock, D. (2004). "A Dynamic Pari-Mutuel Market..." ACM EC'04.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List

import numpy as np

__all__ = ["ParimutuelPool", "DynamicParimutuelMarket"]


@dataclass
class ParimutuelPool:
    """A single static parimutuel pool over ``n`` outcomes.

    Parameters
    ----------
    n_outcomes : number of mutually exclusive outcomes.
    takeout    : fraction ``tau in [0, 1)`` removed from the pool before payout.
    """

    n_outcomes: int
    takeout: float = 0.0
    # stake[outcome] -> list of (bettor, amount)
    _stakes: List[List] = field(default_factory=list, repr=False)

    def __post_init__(self) -> None:
        if self.n_outcomes < 2:
            raise ValueError("need at least 2 outcomes")
        if not (0.0 <= self.takeout < 1.0):
            raise ValueError("takeout must be in [0, 1)")
        self._stakes = [[] for _ in range(self.n_outcomes)]

    def bet(self, bettor: str, outcome: int, amount: float) -> None:
        """Record a wager of ``amount`` by ``bettor`` on ``outcome``."""
        if not (0 <= outcome < self.n_outcomes):
            raise ValueError("outcome out of range")
        if amount <= 0:
            raise ValueError("amount must be positive")
        self._stakes[outcome].append((bettor, float(amount)))

    def pool_on(self, outcome: int) -> float:
        """Total amount wagered on ``outcome``."""
        return float(sum(a for _, a in self._stakes[outcome]))

    @property
    def total_pool(self) -> float:
        return float(sum(self.pool_on(i) for i in range(self.n_outcomes)))

    def implied_probabilities(self) -> np.ndarray:
        """Market-implied probabilities ``W_i / W`` (zeros if pool empty)."""
        w = np.array([self.pool_on(i) for i in range(self.n_outcomes)], float)
        total = w.sum()
        if total == 0:
            return np.zeros(self.n_outcomes)
        return w / total

    def decimal_odds(self, outcome: int) -> float:
        """Current implied decimal odds (payout per unit) on ``outcome``.

        ``(1 - tau) * W / W_i``. Returns ``inf`` if nothing is staked on it.
        """
        w_i = self.pool_on(outcome)
        if w_i == 0:
            return float("inf")
        return (1.0 - self.takeout) * self.total_pool / w_i

    def settle(self, winning_outcome: int) -> Dict[str, float]:
        """Distribute the net pool to winners; return per-bettor payouts.

        A bettor staking ``w`` on the winning outcome receives
        ``w * (1 - tau) * W / W_j``. If nobody backed the winner the net pool is
        returned to all bettors pro rata to their total stake (a common refund
        rule); here we credit it back to backers of the winning outcome only,
        which is empty, so we refund everyone proportionally.
        """
        net = (1.0 - self.takeout) * self.total_pool
        winners = self._stakes[winning_outcome]
        payouts: Dict[str, float] = {}
        w_j = self.pool_on(winning_outcome)
        if w_j == 0:
            # No winning tickets: refund the net pool pro rata across all stakes.
            total = self.total_pool
            if total == 0:
                return payouts
            for outcome in self._stakes:
                for bettor, amt in outcome:
                    payouts[bettor] = payouts.get(bettor, 0.0) + net * amt / total
            return payouts
        for bettor, amt in winners:
            payouts[bettor] = payouts.get(bettor, 0.0) + amt * net / w_j
        return payouts


@dataclass
class DynamicParimutuelMarket:
    r"""Pennock's (2004) dynamic parimutuel market, share-ratio variant.

    Traders buy *shares* of outcomes at a price that moves continuously as
    shares are bought, so early buyers at low prices profit when later buying
    raises the price. On resolution the entire pool is divided among holders of
    winning shares pro rata: the operator's risk is capped at the seed subsidy
    rather than unbounded.

    The share-ratio price function is generated by the cost function

    .. math:: C(s) = \kappa \sqrt{\textstyle\sum_k s_k^2},

    whose gradient :math:`p_i = \kappa s_i / \lVert s \rVert_2` satisfies
    :math:`p_i / p_j = s_i / s_j`. Trades are priced by *integrating* that cost,
    not by the pre-trade price: moving the state from ``s`` to ``s'`` costs
    ``C(s') - C(s)``. Two consequences the linear-price shortcut does not have:

    - *Path independence.* One \$1 purchase and two \$0.50 purchases buy the
      same number of shares. Under a pre-trade linear price they do not (2.0
      shares versus 1.75), which is a free lunch for whoever slices differently.
    - *Cash conservation.* Because :math:`C` is homogeneous of degree one,
      ``money == C(shares)`` at all times, and settlement pays out exactly
      ``money``. The seed shares are held by the house, so the house's stake is
      redeemed alongside the traders' and nothing is created or destroyed.

    A DPM share is not an Arrow security. The payoff per winning share is
    ``money / s_i = 1 / p_i``, so what a share pays depends on the state at
    settlement, not just on which outcome occurred; see Pennock (2004) §4 for
    the resulting valuation subtleties.
    """

    n_outcomes: int
    kappa: float = 1.0
    shares: np.ndarray = field(default=None, repr=False)
    _holdings: Dict[str, np.ndarray] = field(default_factory=dict, repr=False)

    def __post_init__(self) -> None:
        if self.n_outcomes < 2:
            raise ValueError("need at least 2 outcomes")
        if self.kappa <= 0:
            raise ValueError("kappa must be positive")
        if self.shares is None:
            self.shares = np.ones(self.n_outcomes)  # uniform prices, house-owned
        else:
            self.shares = np.asarray(self.shares, float).copy()
            if self.shares.shape != (self.n_outcomes,):
                raise ValueError("shares must have length n_outcomes")
            if np.any(self.shares <= 0):
                raise ValueError("shares must be strictly positive")
        self._seed = self.shares.copy()

    def cost(self, shares=None) -> float:
        """The cost function ``kappa * ||s||_2`` at ``shares`` (default: current)."""
        s = self.shares if shares is None else np.asarray(shares, float)
        return float(self.kappa * np.sqrt(np.sum(s ** 2)))

    @property
    def subsidy(self) -> float:
        """Cash the house put up to seed the market, ``C(s_0)``."""
        return self.cost(self._seed)

    @property
    def money(self) -> float:
        """Cash in the pool. Equals ``C(shares)`` identically."""
        return self.cost()

    def prices(self) -> np.ndarray:
        """Instantaneous prices ``kappa * s_i / ||s||_2``.

        These satisfy the share ratio ``p_i / p_j = s_i / s_j`` and
        ``sum_i p_i^2 = kappa^2``. They do *not* sum to one; normalise by
        :meth:`implied_probabilities` to read them as beliefs.
        """
        return self.kappa * self.shares / np.sqrt(np.sum(self.shares ** 2))

    def implied_probabilities(self) -> np.ndarray:
        """Prices renormalised to sum to one, i.e. ``s_i / sum_k s_k``."""
        return self.shares / self.shares.sum()

    def payoff_per_share(self, outcome: int) -> float:
        """What one share of ``outcome`` pays if it settles now: ``money / s_i``."""
        return self.money / float(self.shares[outcome])

    def shares_for_spend(self, outcome: int, spend: float) -> float:
        r"""Shares of ``outcome`` obtained for ``spend`` cash, in closed form.

        Solving ``C(s + delta e_i) - C(s) = spend`` for ``delta`` gives
        :math:`\delta = \sqrt{((C_0 + \text{spend})/\kappa)^2 - (C_0/\kappa)^2
        + s_i^2} - s_i`, which is exact rather than iterative. ``spend`` may be
        negative (a sale) so long as the radicand stays non-negative.
        """
        if not (0 <= outcome < self.n_outcomes):
            raise ValueError("outcome out of range")
        c0 = self.cost() / self.kappa
        c1 = c0 + spend / self.kappa
        if c1 <= 0:
            raise ValueError("sale would empty the pool")
        radicand = c1 ** 2 - c0 ** 2 + float(self.shares[outcome]) ** 2
        if radicand < 0:
            raise ValueError("sale exceeds the shares outstanding on that outcome")
        return float(np.sqrt(radicand) - self.shares[outcome])

    def buy(self, trader: str, outcome: int, spend: float) -> float:
        """Spend ``spend`` cash on shares of ``outcome``; return shares bought."""
        if spend <= 0:
            raise ValueError("spend must be positive")
        bought = self.shares_for_spend(outcome, spend)
        self.shares[outcome] += bought
        h = self._holdings.setdefault(trader, np.zeros(self.n_outcomes))
        h[outcome] += bought
        return bought

    def sell(self, trader: str, outcome: int, quantity: float) -> float:
        """Sell ``quantity`` shares of ``outcome``; return the cash proceeds."""
        if quantity <= 0:
            raise ValueError("quantity must be positive")
        h = self._holdings.get(trader)
        if h is None or h[outcome] < quantity - 1e-12:
            raise ValueError("trader does not hold that many shares")
        if self.shares[outcome] - quantity <= 0:
            raise ValueError("sale would exhaust the outcome's shares")
        proceeds = self.cost() - self.cost(
            self.shares - quantity * np.eye(self.n_outcomes)[outcome])
        self.shares[outcome] -= quantity
        h[outcome] -= quantity
        return float(proceeds)

    def settle(self, winning_outcome: int) -> Dict[str, float]:
        """Pay the whole pool to winning-share holders pro rata.

        The house's seed shares are redeemed on the same terms, so the returned
        trader payouts plus :meth:`house_settlement` sum to exactly ``money``.
        """
        if not (0 <= winning_outcome < self.n_outcomes):
            raise ValueError("outcome out of range")
        per_share = self.payoff_per_share(winning_outcome)
        return {trader: float(per_share * h[winning_outcome])
                for trader, h in self._holdings.items()
                if h[winning_outcome] > 0}

    def house_settlement(self, winning_outcome: int) -> float:
        """Cash the house recovers on its seed shares. Its loss is at most the subsidy."""
        return float(self.payoff_per_share(winning_outcome)
                     * self._seed[winning_outcome])
